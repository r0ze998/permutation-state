// Copy the browser-safe core of the client SDK (client/src) into the web
// client (permutation-server/web/sdk), which loads it as plain ES modules
// with no build step. The copies are generated: edit client/src and run this
// again (test/web-sdk.test.mjs fails while they differ).
//
//   node scripts/sync-web-sdk.mjs           write permutation-server/web/sdk
//   node scripts/sync-web-sdk.mjs --check   only report; exit 1 if out of date
import { existsSync, mkdirSync, readdirSync, readFileSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

/** The browser-safe set: no node:*, no Buffer, no web3.js or ER SDK, relative imports within the set only. */
export const WEB_SDK = Object.freeze(['sha256.mjs', 'base58.mjs', 'bytes.mjs', 'borsh.mjs', 'codec.mjs', 'decision.mjs', 'talk.mjs', 'batch.mjs',
  'offices.mjs', 'solana-tx.mjs', 'player.mjs']);
export const HEADER = '// generated by permutation-gateway/scripts/sync-web-sdk.mjs — edit permutation-gateway/client/src';
export const SOURCE_DIR = fileURLToPath(new URL('../client/src/', import.meta.url));
export const WEB_SDK_DIR = fileURLToPath(new URL('../../permutation-server/web/sdk/', import.meta.url));

/** Module specifiers a source imports or re-exports (static and dynamic). */
export function importsOf(source) {
  const out = [];
  for (const re of [/\b(?:import|export)\s[^'"`;]*?\bfrom\s*['"]([^'"]+)['"]/g, /\bimport\s*['"]([^'"]+)['"]/g, /\bimport\s*\(\s*['"]([^'"]+)['"]\s*\)/g]) {
    for (const m of source.matchAll(re)) out.push(m[1]);
  }
  return out;
}

/** Source without comments (enough for these modules: none has `//` or `/*` inside a string). */
export const stripComments = source => source.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:'"\\])\/\/.*$/gm, '$1');

/** Why `source` (file `name`) cannot run in a browser as part of the set; empty when it can. */
export function problems(name, source) {
  const out = [];
  const code = stripComments(source);
  for (const spec of importsOf(code)) {
    if (spec.startsWith('node:')) out.push(`${name}: imports ${spec}`);
    else if (!spec.startsWith('./')) out.push(`${name}: imports ${spec} (bare or outside the directory)`);
    else if (!WEB_SDK.includes(spec.slice(2))) out.push(`${name}: imports ${spec}, which is not in the web set`);
  }
  if (/\bBuffer\b/.test(code)) out.push(`${name}: uses Buffer`);
  if (/\bprocess\./.test(code) || /\brequire\s*\(/.test(code)) out.push(`${name}: uses a Node global`);
  return out;
}

/** What web/sdk should hold: file name → content. */
export function expected() {
  return new Map(WEB_SDK.map(name => [name, `${HEADER}\n${readFileSync(SOURCE_DIR + name, 'utf8')}`]));
}

function main() {
  const check = process.argv.includes('--check');
  const want = expected();
  const bad = [...want].flatMap(([name, content]) => problems(name, content));
  if (bad.length) {
    console.error(`not browser-safe:\n  ${bad.join('\n  ')}`);
    process.exit(1);
  }
  const have = existsSync(WEB_SDK_DIR) ? readdirSync(WEB_SDK_DIR) : [];
  const stale = have.filter(f => !want.has(f));
  const changed = [...want].filter(([name, content]) => !have.includes(name) || readFileSync(WEB_SDK_DIR + name, 'utf8') !== content).map(([name]) => name);
  if (check) {
    if (!stale.length && !changed.length) { console.log(`web/sdk is up to date (${want.size} files)`); return; }
    console.error(`web/sdk is out of date: ${[...changed, ...stale.map(f => `${f} (not in the set)`)].join(', ')}\nrun: node permutation-gateway/scripts/sync-web-sdk.mjs`);
    process.exit(1);
  }
  mkdirSync(WEB_SDK_DIR, { recursive: true });
  for (const f of stale) rmSync(WEB_SDK_DIR + f, { recursive: true, force: true });
  for (const name of changed) writeFileSync(WEB_SDK_DIR + name, want.get(name));
  console.log(`web/sdk: ${changed.length} written, ${stale.length} removed, ${want.size - changed.length} unchanged`);
}

if (process.argv[1] && realpathSync(fileURLToPath(import.meta.url)) === realpathSync(process.argv[1])) main();
