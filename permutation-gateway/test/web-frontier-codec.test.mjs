// The Frontier web client's layouts and addresses against the vectors the
// ABI crate writes (contract §3.5: frontier-abi writes, this test reads).
//
//  - web/frontier/abi.mjs is generated from frontier-abi/vectors/{layouts,
//    errors,presets}.json and the beacon block of frontier-vectors.json
//    (fclient); this test is its freshness check (PSF_WRITE_ABI=1 rewrites).
//  - fcodec.mjs decodes every field of every account kind exactly where the
//    layout puts it (checked against an independent DataView reader over
//    random bytes), and refuses a wrong size, magic or season.
//  - faddr.mjs recomputes every with-seed address of addresses.json, the
//    kernel's seed strings (addr-vectors-v1.json), the Season PDA and bump,
//    citizen tags, join shards and host ids; no bump is taken from outside.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import * as abi from '../../permutation-server/web/frontier/abi.mjs';
import * as codec from '../../permutation-server/web/frontier/fcodec.mjs';
import * as addr from '../../permutation-server/web/frontier/faddr.mjs';
import * as geo from '../../permutation-server/web/frontier/fgeo.mjs';
import { decode as fromBase58 } from '../../permutation-server/web/sdk/base58.mjs';

const REPO = new URL('../../', import.meta.url);
const json = rel => JSON.parse(readFileSync(new URL(rel, REPO), 'utf8'));
const ABI_FILE = new URL('permutation-server/web/frontier/abi.mjs', REPO);
const hex = h => Uint8Array.from(Buffer.from(h, 'hex'));

// ================================================================== the generated table
const compactFields = fields => fields.map(f => [f.name, f.off, f.len, f.ty]);

/** The exact text of web/frontier/abi.mjs. */
export function abiSource() {
  const layouts = json('frontier-abi/vectors/layouts.json');
  const errors = json('frontier-abi/vectors/errors.json');
  const presets = json('frontier-abi/vectors/presets.json');
  const beacon = json('permutation-gateway/test/frontier-vectors.json').beacon;
  const accounts = {};
  for (const a of layouts.accounts) {
    accounts[a.kind] = { code: a.code, magic: a.magic, size: a.size, chained: a.chained, tag: a.seed_tag, rawKeyLen: a.raw_key_len, fields: compactFields(a.fields) };
  }
  const records = {};
  for (const r of layouts.records) records[r.name] = { size: r.size, fields: compactFields(r.fields) };
  const q = beacon.quicknet, t = beacon.test_key;
  const quicknet = { genesis: q.genesis_time, period: q.period, publicKey: q.public_key, pkHash: beacon.quicknet_pk_hash, chainHash: q.chain_hash, schemeId: q.schemeID };
  assert.equal(quicknet.publicKey, presets.quicknet.public_key, 'fclient and frontier-abi agree on the quicknet key');
  assert.equal(quicknet.pkHash, presets.quicknet.pk_hash);
  const testBeacon = { genesis: t.info.genesis_time, period: t.info.period, publicKey: t.info.public_key, pkHash: t.pk_hash, chainHash: t.info.chain_hash, schemeId: t.info.schemeID };
  const lines = [
    '// generated by permutation-gateway/test/web-frontier-codec.test.mjs from',
    '// frontier-abi/vectors/{layouts,errors,presets}.json and the beacon block of',
    '// permutation-gateway/test/frontier-vectors.json — do not edit',
    '// (PSF_WRITE_ABI=1 node --test test/web-frontier-codec.test.mjs rewrites it).',
    `export const ABI_VERSION = ${layouts.abi_version};`,
    `export const RENT_PER_BYTE = ${layouts.rent_per_byte};`,
    `export const RULESET_HASH = '${presets.ruleset_hash}';`,
    `/** drand quicknet: the only beacon a deployable season uses. */`,
    `export const QUICKNET = Object.freeze(${JSON.stringify(quicknet)});`,
    `/** The deterministic local test key (I-53): accepted only on a localnet season. */`,
    `export const TEST_BEACON = Object.freeze(${JSON.stringify(testBeacon)});`,
    `/** Program error codes (§5.4): [code, name]. */`,
    `export const ERRORS = Object.freeze(${JSON.stringify(errors.errors.map(e => [e.code, e.name]))});`,
    `/** Account layouts (§4.3, §5.3): fields are [name, offset, length, type]. */`,
    'export const ACCOUNTS = Object.freeze({',
    ...Object.entries(accounts).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`),
    '});',
    '/** Sub-records (transit, entry, site mirror, …). */',
    'export const RECORDS = Object.freeze({',
    ...Object.entries(records).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`),
    '});',
    '',
  ];
  return lines.join('\n');
}

test('abi.mjs is generated from the ABI vectors (freshness)', () => {
  const want = abiSource();
  if (process.env.PSF_WRITE_ABI === '1') writeFileSync(ABI_FILE, want);
  assert.equal(readFileSync(ABI_FILE, 'utf8'), want, 'web/frontier/abi.mjs is stale: PSF_WRITE_ABI=1 node --test test/web-frontier-codec.test.mjs');
  assert.equal(abi.ACCOUNTS.Season.size, 2048);
  assert.equal(Object.keys(abi.ACCOUNTS).length, 17, '17 account kinds (§0)');
  assert.equal(abi.ERRORS.length, json('frontier-abi/vectors/errors.json').errors.length);
});

// ================================================================== decoding
/** An independent reader: the value of field f at `base` in `b`. */
function reference(b, base, [, off, len, ty]) {
  const dv = new DataView(b.buffer, b.byteOffset, b.byteLength), o = base + off;
  const s = { u8: () => dv.getUint8(o), u16: () => dv.getUint16(o, true), u32: () => dv.getUint32(o, true), u64: () => dv.getBigUint64(o, true), i16: () => dv.getInt16(o, true), i32: () => dv.getInt32(o, true), i64: () => dv.getBigInt64(o, true) }[ty];
  if (s) return s();
  if (/^\[u8;/.test(ty)) return Uint8Array.from(b.subarray(o, o + len));
  const m = /^\[(\w+);(\d+)\]$/.exec(ty);
  if (m) {
    const w = { u16: 2, u32: 4, u64: 8, i64: 8 }[m[1]];
    return Array.from({ length: +m[2] }, (_, i) => reference(b, o + i * w, ['', 0, w, m[1]]));
  }
  const r = /^rec:(\w+) x(\d+)$/.exec(ty);
  const rec = abi.RECORDS[r[1]];
  const one = i => Object.fromEntries(rec.fields.filter(f => f[3] !== 'rsv').map(f => [codec.camel(f[0]), reference(b, o + i * rec.size, f)]));
  return +r[2] === 1 ? one(0) : Array.from({ length: +r[2] }, (_, i) => one(i));
}

test('every field of every account decodes from its offset (random bytes, 3 rounds per kind)', () => {
  for (const [kind, layout] of Object.entries(abi.ACCOUNTS)) {
    // The layout tiles the account: fields in order, no gap, ending at the size.
    let at = 0;
    for (const f of layout.fields) { assert.equal(f[1], at, `${kind}.${f[0]} offset`); at += f[2]; }
    assert.equal(at, layout.size, `${kind} fields end at its size`);
    for (let round = 0; round < 3; round++) {
      const b = Uint8Array.from(randomBytes(layout.size));
      b.set(Buffer.from(layout.magic, 'latin1'), 0);
      const d = codec.decode(kind, b);
      for (const f of layout.fields) {
        if (f[3] === 'rsv') { assert.ok(!(codec.camel(f[0]) in d), `${kind}: reserved ${f[0]} left out`); continue; }
        assert.deepEqual(d[codec.camel(f[0])], reference(b, 0, f), `${kind}.${f[0]}`);
      }
    }
  }
  for (const [name, rec] of Object.entries(abi.RECORDS)) {
    let at = 0;
    for (const f of rec.fields) { assert.equal(f[1], at, `${name}.${f[0]}`); at += f[2]; }
    assert.equal(at, rec.size, `${name} size`);
  }
});

test('decode refuses a wrong size, magic or season, and reads the Season tombstone', () => {
  const b = new Uint8Array(2048);
  b.set(Buffer.from('PSF1SEAS', 'latin1'));
  new DataView(b.buffer).setBigUint64(8, 7n, true);
  assert.equal(codec.decode('Season', b, { seasonId: 7 }).seasonId, 7n);
  assert.throws(() => codec.decode('Season', b, { seasonId: 8 }), e => e.code === 'WrongSeason');
  assert.throws(() => codec.decode('Season', b.subarray(0, 2047)), e => e.code === 'WrongSize');
  assert.throws(() => codec.decode('Holding', b), e => e.code === 'WrongSize');
  const p = new Uint8Array(4096); p.set(Buffer.from('PSF1HOLD', 'latin1'));
  assert.throws(() => codec.decode('Province', p), e => e.code === 'WrongMagic');
  assert.throws(() => codec.decode('Nope', p), e => e.code === 'WrongKind');
  const tomb = codec.decode('Season', b.subarray(0, 128));
  assert.equal(tomb.status, 0);
  assert.ok(!('genesisTs' in tomb), 'a tombstone has no fields past 128 B');
});

test('season helpers: effective status and W(b) (§5.1, §5.3)', () => {
  const s = { status: 2, genesisTs: 1000n, revealWindow: 600, windowNext: 900, windowFromBell: 200 };
  assert.equal(codec.effectiveStatus(s, 999), 'Seeded');
  assert.equal(codec.effectiveStatus(s, 1000), 'Running');
  assert.equal(codec.effectiveStatus({ ...s, status: 4 }, 5000), 'Ended');
  assert.equal(codec.windowAt(s, 199), 600);
  assert.equal(codec.windowAt(s, 200), 900);
  assert.equal(codec.windowAt({ ...s, windowFromBell: codec.NO_WINDOW_CHANGE }, 10 ** 6), 600);
});

// ================================================================== addresses
test('with-seed addresses equal frontier-abi/vectors/addresses.json', () => {
  const v = json('frontier-abi/vectors/addresses.json');
  let n = 0;
  for (const a of v.accounts) {
    const address = addr.withSeed(v.season_pda.b58, a.seed, v.program_id.b58);
    assert.equal(address, a.address, `${a.kind} ${a.seed}`);
    // The seed from named key fields, where the vector names them.
    if (a.key && addr.RAW[a.kind]) assert.equal(addr.seedOf(a.kind, a.key), a.seed, `${a.kind} seed`);
    if (!a.key) assert.equal(addr.seedOf(a.kind), a.seed);
    n++;
  }
  assert.ok(n >= 15);
});

test('seed strings equal the kernel\'s (addr-vectors-v1.json) for every kind the web derives', () => {
  const v = json('permutation-rules/vectors/addr-vectors-v1.json');
  const byTag = Object.fromEntries(Object.entries(abi.ACCOUNTS).filter(([, a]) => a.tag).map(([k, a]) => [a.tag, k]));
  let n = 0;
  for (const s of v.seeds) {
    const kind = byTag[s.kind];
    if (!kind) continue;
    const k = { ...s.args };
    for (const w of ['wallet', 'beneficiary']) if (typeof k[w] === 'string') k[w] = hex(k[w]);
    if ('bell' in k) k.bell = Number(k.bell);
    assert.equal(addr.seedOf(kind, k), s.seed, `${s.kind} ${JSON.stringify(s.args)}`);
    n++;
  }
  assert.ok(n > 60, `${n} seeds checked`);
  for (const t of v.tags) {
    const w = hex(t.wallet);
    assert.equal(Buffer.from(addr.citizenTag15(w)).toString('hex'), t.citizen_tag15);
    assert.equal(Buffer.from(addr.keeperTag8(w)).toString('hex'), t.keeper_tag8);
  }
  for (const a of v.addresses) {
    const out = addr.withSeed(hex(a.base), a.seed, hex(a.program));
    assert.equal(Buffer.from(fromBase58(out)).toString('hex'), a.address, a.seed);
  }
});

test('the Season PDA and its bump are found here; citizen, shard and holding addresses follow', () => {
  const f = json('permutation-gateway/test/frontier-vectors.json').addresses;
  const A = addr.seasonAddresses(f.program, f.season_id);
  assert.equal(A.season, f.season);
  assert.equal(A.bump, f.bump);
  const c = f.citizen;
  assert.equal(Buffer.from(addr.citizenTag15(c.wallet)).toString('hex'), c.tag15);
  assert.equal(A.of('Citizen', { wallet: c.wallet }), c.address);
  assert.equal(addr.citizenTag(c.address).toString(), c.citizen_tag);
  assert.equal(addr.joinShardOf(c.wallet), c.join_shard);
  for (const s of f.seeds) {
    if (s.kind === 'po' || s.kind === 'sv') continue; // reserved kinds: the web never derives them
    assert.equal(addr.withSeed(A.season, s.seed, A.programId), s.address, s.seed);
  }
  for (const h of f.host_ids) {
    const id = addr.hostId(h);
    assert.equal(id.toString(), h.id);
    assert.equal(A.holdingOfHost(id), h.holding);
  }
  const t = json('frontier-abi/vectors/addresses.json').tags;
  assert.equal(addr.joinShardOf(t.wallet), t.join_shard);
});

test('host ids: the kernel\'s vectors, the inverse, and the invalid id', () => {
  const v = json('permutation-rules/vectors/addr-vectors-v1.json');
  for (const h of v.host_ids) {
    const id = addr.hostId(h);
    assert.equal(id.toString(), h.host_id, JSON.stringify(h));
    if (h.host_id === addr.HOST_ID_INVALID.toString()) { assert.equal(addr.hostParts(id), null); continue; }
    assert.equal(geo.provinceIndex(h.p, h.q), h.province_index);
    assert.deepEqual(addr.hostParts(id), { provinceIndex: h.province_index, p: h.p, q: h.q, site: h.site, gen: h.gen, seq: h.seq });
  }
  assert.equal(addr.hostId({ p: 0, q: 0, site: 12, gen: 0, seq: 0 }), addr.HOST_ID_INVALID);
  assert.equal(addr.hostParts(addr.HOST_ID_INVALID), null);
  for (let i = 0; i < 2000; i += 7) assert.equal(geo.provinceIndex(...Object.values(geo.provinceFromIndex(i))), i);
  assert.equal(geo.provinceFromIndex(geo.provincesWithin(128)), null);
});
